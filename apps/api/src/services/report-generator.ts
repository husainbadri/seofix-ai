import PDFDocument from 'pdfkit';
import { stringify } from 'csv-stringify/sync';

export interface WhiteLabelConfig {
  agencyName: string;
  brandColor?: string;
  logoUrl?: string;
}

export class ReportGeneratorService {
  public generateCSV(auditReport: any): string {
    const records = (auditReport.allIssues || []).map((issue: any) => ({
      PageUrl: issue.pageUrl,
      Category: issue.category,
      SubSkill: issue.subSkill,
      Severity: issue.severity,
      Score: issue.score,
      Title: issue.title,
      Description: issue.description,
      Recommendation: issue.recommendation,
      EstimatedImpact: issue.estimatedImpact
    }));

    return stringify(records, { header: true });
  }

  public generateExcelData(auditReport: any) {
    return {
      metadata: {
        domain: auditReport.targetDomain,
        generatedAt: new Date().toISOString(),
        overallScore: auditReport.overallScore
      },
      categoryScores: {
        technical: auditReport.technicalScore,
        performance: auditReport.performanceScore,
        content: auditReport.contentScore,
        security: auditReport.securityScore,
        accessibility: auditReport.accessibilityScore,
        keyword: auditReport.keywordScore,
        backlink: auditReport.backlinkScore
      },
      issues: auditReport.allIssues
    };
  }

  public async generateWhiteLabelPDFBuffer(auditReport: any, branding: WhiteLabelConfig): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({ margin: 40 });
        const buffers: Buffer[] = [];

        doc.on('data', buffers.push.bind(buffers));
        doc.on('end', () => resolve(Buffer.concat(buffers)));

        const primaryColor = branding.brandColor || '#4F46E5';

        // Header Section
        doc.fillColor(primaryColor).fontSize(24).text(branding.agencyName.toUpperCase(), { align: 'left' });
        doc.fillColor('#6B7280').fontSize(10).text(`SEO Audit & Intelligence Report - ${auditReport.targetDomain}`, { align: 'left' });
        doc.moveDown(1.5);

        // Divider
        doc.strokeColor(primaryColor).lineWidth(2).moveTo(40, doc.y).lineTo(570, doc.y).stroke();
        doc.moveDown(1.5);

        // Executive Summary Box
        doc.fillColor('#111827').fontSize(16).text('Executive Summary', { underline: true });
        doc.moveDown(0.5);
        doc.fillColor('#374151').fontSize(10).text(auditReport.executiveSummary, { width: 500, align: 'left' });
        doc.moveDown(1.5);

        // Score Overview Table
        doc.fillColor('#111827').fontSize(14).text('Overall Health & Category Scores');
        doc.moveDown(0.5);

        const scores = [
          `Overall Score: ${auditReport.overallScore}/100`,
          `Technical SEO: ${auditReport.technicalScore}/100`,
          `Performance: ${auditReport.performanceScore}/100`,
          `Content Quality: ${auditReport.contentScore}/100`,
          `Security: ${auditReport.securityScore}/100`,
          `Accessibility: ${auditReport.accessibilityScore}/100`
        ];

        scores.forEach(s => {
          doc.fillColor('#4B5563').fontSize(10).text(`•  ${s}`);
        });

        doc.moveDown(1.5);

        // Top Critical Issues
        doc.fillColor('#111827').fontSize(14).text('Actionable Priorities & Quick Wins');
        doc.moveDown(0.5);

        const topIssues = (auditReport.allIssues || []).slice(0, 5);
        topIssues.forEach((issue: any, index: number) => {
          doc.fillColor('#DC2626').fontSize(11).text(`${index + 1}. [${issue.severity}] ${issue.title}`);
          doc.fillColor('#4B5563').fontSize(9).text(`URL: ${issue.pageUrl}`);
          doc.fillColor('#374151').fontSize(9).text(`Fix: ${issue.recommendation}`, { width: 500 });
          doc.moveDown(0.8);
        });

        // Footer
        doc.moveDown(2);
        doc.fillColor('#9CA3AF').fontSize(8).text(`Generated by ${branding.agencyName} via AI SEO Platform. Confidential.`, { align: 'center' });

        doc.end();
      } catch (err) {
        reject(err);
      }
    });
  }
}
